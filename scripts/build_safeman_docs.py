#!/usr/bin/env python3
"""
build_safeman_docs.py — SafeMan learner manuals + sample certificate.

Rule 1: every manual is generated by CLONING the SafeMan green Word templates
(templates/safeman_green/, themselves cloned from Oryx_Build_Package_v3) and
injecting course content from public/data/safeman_courses.json using the
template's own style vocabulary (OxEyebrow, Heading1, Heading2, OxBody, OxLead,
OxList, OxTable, OxCalloutText, OxSmall). No styles are invented.

Usage:  python3 scripts/build_safeman_docs.py
Output: public/manuals/safeman/<COURSE-ID>.docx + .pdf  (+ SAMPLE certificate)
"""
import os, sys, json, subprocess
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TPL = os.path.join(ROOT, "templates", "safeman_green", "04_Student_Module_Print.docx")
TPL_CERT = os.path.join(ROOT, "templates", "safeman_green", "08_Certificate_Print.docx")
DATA = os.path.join(ROOT, "public", "data", "safeman_courses.json")
OUT = os.path.join(ROOT, "public", "manuals", "safeman")
os.makedirs(OUT, exist_ok=True)

GREEN = RGBColor(0x14, 0x53, 0x2D)
SAGE = "C6D8C8"

# Cover title frame fits 2 lines at the template's 32pt. Long course names get
# template-safe short cover titles; the full title stays in the body and header.
SHORT_TITLES = {
    "SM-FIRE": "Basic Firefighting & Fire Marshal",
    "SM-FA1": "Workplace First Aid Responder",
    "SM-CPR": "Basic Life Support, CPR & Choking",
    "SM-WAH": "Working at Heights & Fall Arrest",
    "SM-CSE": "Confined Space & Gas Testing",
    "SM-LOTO": "Lockout / Tagout Energy Control",
    "SM-HIRA": "Task HIRA & Toolbox Facilitator",
    "SM-HCS": "Hazardous Chemicals, GHS & Spills",
    "SM-MINE": "Mining & Quarrying Masterclass",
    "SM-PETRO": "Petrochemical & Hydrogen Masterclass",
    "SM-CONST": "Construction & Contractors Masterclass",
}

def body_children(doc):
    return list(doc.element.body)

def clear_after_cover(doc, sentinel="info@oryxinstitute.org"):
    """Keep the cover (everything up to and incl. the sentinel paragraph), drop the rest."""
    body = doc.element.body
    children = list(body)
    last_keep = None
    for ch in children:
        texts = "".join(t.text or "" for t in ch.iter(qn("w:t")))
        last_keep = ch
        if sentinel in texts:
            break
    if last_keep is not None:
        idx = children.index(last_keep)
        for ch in children[idx + 1:]:
            if ch.tag == qn("w:sectPr"):
                continue
            body.remove(ch)

def page_break(doc):
    p = doc.add_paragraph()
    p.add_run().add_break(WD_BREAK.PAGE)
    return p

def set_para_text(p, text):
    runs = p.runs
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""

def cover_edit(doc, mapping):
    """XML-level cover edit: reaches paragraphs inside text boxes (w:txbxContent) too."""
    done = set()
    for p in doc.element.body.iter(qn("w:p")):
        text = "".join(t.text or "" for t in p.iter(qn("w:t"))).strip()
        for key, val in mapping.items():
            if text == key and key not in done:
                runs = list(p.findall(qn("w:r")))
                if runs:
                    for t in runs[0].findall(qn("w:t")):
                        t.text = val
                    for r in runs[1:]:
                        for t in r.findall(qn("w:t")):
                            t.text = ""
                    done.add(key)
    return done

def edit_header(doc, code, title):
    for sec in doc.sections:
        hdr = sec.header
        for p in hdr.paragraphs:
            t = p.text
            if "SM-" in t or "Tools of Measurement" in t:
                new = t.replace("SM-1101", code).replace("ORX 1101", code).replace("Tools of Measurement", title)
                # keep the tab stop between code and title
                parts = new.split("\t")
                if len(parts) == 2 and p.runs:
                    set_para_text(p, "")
                    p.runs[0].text = parts[0] + "\t" + parts[1]
                else:
                    set_para_text(p, new)

def P(doc, text, style):
    p = doc.add_paragraph(text, style=style)
    return p

def H1(doc, text): return P(doc, text, "Heading1")
def H2(doc, text): return P(doc, text, "Heading2")
def BODY(doc, text): return P(doc, text, "OxBody")
def SMALL(doc, text): return P(doc, text, "OxSmall")
def CALLOUT(doc, label, text):
    P(doc, label, "OxCalloutLabel")
    return P(doc, text, "OxCalloutText")

def set_cell_borders(cell, color=SAGE):
    tcPr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), color)
        borders.append(el)
    tcPr.append(borders)

def TABLE(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        p = c.paragraphs[0]
        p.style = doc.styles["OxTableHead"]
        p.add_run(h)
        set_cell_borders(c)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            c = cells[i]
            c.text = ""
            p = c.paragraphs[0]
            p.style = doc.styles["OxTable"]
            p.add_run(str(v))
            set_cell_borders(c)
    return t

def to_pdf(docx_path):
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf",
                    "--outdir", os.path.dirname(docx_path), docx_path],
                   check=True, capture_output=True, timeout=180)
    return docx_path.replace(".docx", ".pdf")

def build_manual(course):
    doc = Document(TPL)
    # Strip the template's sample body FIRST (original text sentinels), leaving cover frames.
    clear_after_cover(doc, sentinel="info@oryxinstitute.org")
    meta = f"{course['subtitle']}   \u00b7   Pass mark {course['pass_mark']}%   \u00b7   {len(course['modules'])} modules"
    cover_edit(doc, {
        "SM-1101": course["id"],
        "Tools of Measurement": SHORT_TITLES.get(course["id"], course["title"]),
        "Diploma in Applied Engineering": "SafeMan\u2122 by Oryx Institute \u00b7 safeman.oryxinstitute.org",
        "Level 5   \u00b7   12 credits   \u00b7   Semester 1": meta,
    })
    edit_header(doc, course["id"], course["title"])
    page_break(doc)

    # WELCOME block
    P(doc, "WELCOME", "OxEyebrow")
    H1(doc, course["title"])
    BODY(doc, f"{course['title']} \u2014 {course['subtitle']}. This SafeMan course is engineered for corporate "
              f"audit readiness against: {'; '.join(course['standards'])}.")
    CALLOUT(doc, "REGULATORY DISCLOSURE \u2014 READ FIRST",
            "SafeMan\u2122 is a proprietary inter-organizational safety management and operational competency benchmark "
            "developed by Oryx Institute (safeman.oryxinstitute.org). Courses are engineered in alignment with ISO 45001:2018, "
            "ISO 14001:2015, ISO 31000, ILO-OSH guidelines, and pre-referenced against Namibia Training Authority (NTA) Unit "
            "Standards and Namibian Government Notice 156 of 1997 for corporate audit readiness. SafeMan credentials verify "
            "industry competency and attendance between organizations and are non-NQA credit-bearing.")
    P(doc, "Contact: info@oryxinstitute.org", "OxSmall")
    P(doc, "Author: Tangi Iigonda \u00b7 Institution: Oryx Institute | Oryx Safety Academy", "OxSmall")

    # How to use
    H2(doc, "How to use this module pack")
    BODY(doc, "Work through the modules in order. Each module states its focus and the key points you are "
              "expected to carry into practice. Diagrams referenced as web assets accompany the online reader at "
              "safeman.oryxinstitute.org. After the modules, sit the knowledge check: "
              f"{course['questions_in_exam']} questions, pass mark {course['pass_mark']}%, closed book.")
    if course.get("practicum"):
        BODY(doc, "This is a practicum course: after passing the knowledge check you must complete the "
                  "assessor practicum checklist with a qualified assessor before your SafeMan credential is issued. "
                  "A practical demonstration video slot is reserved in the online reader for every module.")

    # Modules
    P(doc, "MODULES", "OxEyebrow")
    for i, m in enumerate(course["modules"], 1):
        H2(doc, f"Module {i} \u2014 {m['title'].split(' \u2014 ')[-1] if ' \u2014 ' in m['title'] else m['title']}")
        BODY(doc, m["focus"])
        P(doc, "Key points", "OxLead")
        for kp in m.get("keypoints", []):
            P(doc, kp, "OxList")
        if m.get("diagram"):
            P(doc, f"Diagram: {m['diagram']}", "OxCaption")
        P(doc, "Practical video recording scheduled \u2014 follow the step-by-step illustrated checklist below.",
          "OxCaption") if course.get("practicum") else None

    # Assessment
    P(doc, "ASSESSMENT", "OxEyebrow")
    H2(doc, "Knowledge check")
    BODY(doc, f"The closed-book knowledge check draws {course['questions_in_exam']} questions from the bank "
              f"reproduced in Appendix A. Pass mark {course['pass_mark']}%. Your SafeMan credential is issued "
              f"after the knowledge check{' and the practicum sign-off' if course.get('practicum') else ''}, "
              f"and remains valid for {course['cert_validity_months']} months from issue.")

    if course.get("practicum"):
        H2(doc, course["practicum"]["title"])
        BODY(doc, "Pass standard: " + course["practicum"]["pass_standard"])
        TABLE(doc, ["#", "Assessor verification step", "Initials & date"],
              [[str(i + 1), s, ""] for i, s in enumerate(course["practicum"]["steps"])])
        SMALL(doc, "Assessor name, role/qualification and company are captured on the sign-off screen of the "
                   "SafeMan platform and bound into the QR-verified certificate record.")

    # Appendix: question bank
    P(doc, "APPENDIX A \u2014 QUESTION BANK", "OxEyebrow")
    H2(doc, "Knowledge check bank")
    for i, q in enumerate(course["quiz"], 1):
        P(doc, f"Q{i}. {q['q']}", "OxBody")
        for j, opt in enumerate(q["o"]):
            P(doc, f"{'ABCD'[j]}.  {opt}", "OxList")
    P(doc, "Answer key", "OxLead")
    letters = "ABCD"
    key_rows = []
    row = []
    for i, q in enumerate(course["quiz"], 1):
        row.append(f"Q{i}={letters[q['a']]}")
        if len(row) == 6:
            key_rows.append(row)
            row = []
    if row:
        key_rows.append(row)
    for r in key_rows:
        SMALL(doc, "   ".join(r))

    out = os.path.join(OUT, f"{course['id']}.docx")
    doc.save(out)
    return out

def build_sample_certificate(course):
    doc = Document(TPL_CERT)
    cover_edit(doc, {
        "[Recipient name]": "Tate-Ati Tangi Iigonda (SAMPLE)",
        "[Programme or course name]": f"{course['id']} \u2014 {course['title']}",
        "3 November 2026": "3 November 2026   \u00b7   Serial SM-2026-" + course["id"].split("-")[-1] + "-00001",
    })
    P(doc, "SAFE MAN \u00b7 CERTIFICATE OF COMPETENCY & ATTENDANCE \u00b7 NON-NQA CREDIT-BEARING \u00b7 VERIFY AT SAFEMAN.ORYXINSTITUTE.ORG", "OxSmall")
    out = os.path.join(OUT, f"SAMPLE-CERTIFICATE-{course['id']}.docx")
    doc.save(out)
    return out

def main():
    courses = json.load(open(DATA))["courses"]
    only = sys.argv[1:] if len(sys.argv) > 1 else None
    made = []
    for c in courses:
        if only and c["id"] not in only:
            continue
        p = build_manual(c)
        made.append(p)
        print("  manual", os.path.basename(p))
    if not only:
        cert = build_sample_certificate(courses[3])  # SM-FIRE
        print("  certificate", os.path.basename(cert))
        made.append(cert)
    for p in made:
        try:
            to_pdf(p)
            print("  pdf    ", os.path.basename(p).replace(".docx", ".pdf"))
        except Exception as e:
            print("  PDF FAILED", p, e)
    print(f"Done: {len(made)} documents in public/manuals/safeman/")

if __name__ == "__main__":
    main()
